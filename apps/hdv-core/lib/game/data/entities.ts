export function getEntityById(id: string): Entity | undefined {
  return ALL_ENTITIES.find((e) => e.id === id)
}

export function resolveRPS(
  attacker: Entity,
  defender: Entity,
): 'win' | 'lose' | 'draw' {
  if (ROLE_DEFEATS[attacker.role] === defender.role) return 'win'
  if (ROLE_DEFEATS[defender.role] === attacker.role) return 'lose'
  return 'draw'
}

export function getRandomEncounter(
  faction: FactionId,
  tier: 1 | 2 | 3 | 4 | 5,
): Entity {
  const pool = ALL_ENTITIES.filter(
    (e) => e.faction === faction && e.tier <= tier,
  )
  if (pool.length === 0) {
    return ALL_ENTITIES.find((e) => e.faction === faction) ?? ALL_ENTITIES[0]
  }
  return pool[Math.floor(Math.random() * pool.length)]
}
